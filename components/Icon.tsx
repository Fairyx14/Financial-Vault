interface IconProps {
  paths: string[];
  className?: string;
  size?: number;
}

/** Decorative line icon. Hidden from screen readers; the surrounding text carries the meaning. */
export default function Icon({ paths, className, size = 24 }: IconProps) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.6}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {paths.map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  );
}
